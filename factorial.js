// factorial of a number using whil loop
// 5 = 1*2*3*4*5
// 6 = 1*2*3*4*5*6


var i=1;
var n= 5;

var result =1;

while(i<=n){
    result = result*i;
    i++
}
console.log(`factorial of ${5} is ${result}`);



